# ---------------------------------------------------------------------------
# Веса тем для ``Significance`` (D-36, ТЗ-B11).
#
# DESIGN (docs/tg/docs/DESIGN.md §4.3/§4.4/§6) ЗАКРЕПЛЯЕТ, что множитель
# ``TopicWeight`` существует и что «релизы/агенты выше мемов», но ЧИСЛА не
# задаёт. Поэтому вес — осознанная, владельцу видимая таблица (ниже), а не
# выдумка внутри формулы. Список тем — единый (17 тем, SCHEMA.md §2.8); в
# DESIGN §4.3 приведён более ранний черновой набор из 10 slug'ов
# (``model_release``, ``agents``, …) — он НЕ используется, чтобы не заводить
# вторую таксономию рядом с YouTube/отчётом (см. комментарий выше о едином
# списке).
#
# Инварианты, важные для ранжирования:
#   * тема не распознана (нет строки ``classification``, ``is_ai != 1`` или
#     ``topic IS NULL``) → вес РОВНО ``1.0`` (нейтрально): не наказываем пост
#     за то, что классификатор его ещё не видел (иначе рейтинг поехал бы от
#     порядка прогонов);
#   * вес — только множитель, он НЕ спасает пост с нулевой вовлечённостью
#     (``Eng``/``Fr`` обнуляют произведение) и не отменяет ``DupPenalty``;
#   * «мемы/влоги/прочее» опущены ниже 1.0, релизы/агенты/разработка — выше.
# ---------------------------------------------------------------------------
TOPIC_WEIGHTS: dict[str, float] = {
    "модели и релизы": 1.40,
    "агенты и автоматизация": 1.30,
    "кодинг и разработка": 1.20,
    "чипы и железо": 1.15,
    "дата-центры и энергия": 1.15,
    "наука и медицина": 1.10,
    "регулирование и безопасность": 1.05,
    "деньги и сделки": 1.05,
    "стартапы и бизнес": 1.05,
    "запуски и анонсы": 1.00,
    "роботы и физический ИИ": 1.00,
    "ИИ-инструменты для обычных людей": 1.00,
    "медиа и творчество": 0.90,
    "дизайн и креатив": 0.90,
    "обучение и навыки": 0.90,
    "влоги и личный опыт": 0.70,
    "прочее": 0.60,
}

#: Нейтральный вес: тема неизвестна/не ИИ. Формулу менять нельзя без приёмки.
NEUTRAL_TOPIC_WEIGHT = 1.0


def topic_weight_of(topic: str | None) -> float:
    """Вес темы для ``TopicWeight``. Неизвестная/пустая тема → нейтральный 1.0."""
    if not topic:
        return NEUTRAL_TOPIC_WEIGHT
    return float(TOPIC_WEIGHTS.get(topic, NEUTRAL_TOPIC_WEIGHT))
